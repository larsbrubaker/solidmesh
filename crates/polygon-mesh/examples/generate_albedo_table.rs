//! Writes `crates/polygon-mesh/src/ray_tracer/scattering/albedo_table.rs`, the GGX directional
//! albedo the scattering model keeps energy with: `cargo run --release -p solidmesh-mesh
//! --example generate_albedo_table`. Prints nothing else. The table's `[A, B]` cells, the
//! cosine-weighted mean of each row and how they are computed are in `scattering::albedo`; the
//! scattering tests fail if the checked-in table no longer matches the production lobe.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use solidmesh_mesh::ray_tracer::{
    albedo_column_cos, albedo_row_alpha, directional_albedo_by_quadrature, mean_albedo_of_row,
    AlbedoTable, ALBEDO_TABLE_SIZE, GENERATION_SUBDIVISIONS,
};

const HEADER: &str = "\
//! GENERATED by `cargo run --release -p solidmesh-mesh --example generate_albedo_table`; do not
//! edit. The directional albedo of a GGX reflection as `[roughness row][cosine column] -> [A, B]`,
//! where Schlick Fresnel `F0 + (F90 - F0)(1 - c)^5` gives an albedo of `F0 * A + F90 * B`, and
//! each row's cosine-weighted mean over the hemisphere. `albedo` describes the grid.

use super::albedo::{AlbedoTable, ALBEDO_TABLE_SIZE};
";

fn main() {
    let mut table: AlbedoTable = [[[0.0; 2]; ALBEDO_TABLE_SIZE]; ALBEDO_TABLE_SIZE];
    for (row, cells) in table.iter_mut().enumerate() {
        for (column, cell) in cells.iter_mut().enumerate() {
            *cell = directional_albedo_by_quadrature(
                albedo_column_cos(row, column),
                albedo_row_alpha(row),
                GENERATION_SUBDIVISIONS,
            );
        }
    }
    let mut text = String::from(HEADER);
    text.push_str("\n#[rustfmt::skip]\npub(super) const ALBEDO: AlbedoTable = [\n");
    for row in &table {
        text.push_str("    [\n");
        for cells in row.chunks(3) {
            text.push_str("        ");
            for cell in cells {
                write!(text, "[{:?}, {:?}], ", cell[0], cell[1]).expect("writing to a String");
            }
            text.pop();
            text.push('\n');
        }
        text.push_str("    ],\n");
    }
    text.push_str("];\n");
    text.push_str(
        "\n#[rustfmt::skip]\npub(super) const MEAN_ALBEDO: [[f64; 2]; ALBEDO_TABLE_SIZE] = [\n",
    );
    for row in 0..ALBEDO_TABLE_SIZE {
        let [a, b] = mean_albedo_of_row(&table, row);
        writeln!(text, "    [{a:?}, {b:?}],").expect("writing to a String");
    }
    text.push_str("];\n");
    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("src/ray_tracer/scattering/albedo_table.rs");
    fs::write(&path, text).unwrap_or_else(|error| panic!("writing {path:?}: {error}"));
}
